def _faction_color(faction: str) -> str:
    _map = {
        "iron fang":           "#8B4513",
        "argent blades":       "#808080",
        "glass sigil":         "#4682B4",
        "serpent choir":       "#DAA520",
        "obsidian lotus":      "#6B3FA0",
        "patchwork saints":    "#8B0000",
        "wardens of ash":      "#A0522D",
        "tower authority":     "#2F4F4F",
        "adventurers guild":   "#2E7D32",
        "guild of ashen scrolls":"#8D6E3A",
    }
    f = (faction or "").lower()
    for k, v in _map.items():
        if k in f:
            return v
    return "#3a6898"



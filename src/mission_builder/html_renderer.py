def render_maps_page(
    novel_title: str,
    faction: str,
    image_paths: list,          # list of Path objects relative to module dir
    manifest_json: str = "",
) -> str:
    """
    Render maps.html directly from PNG paths, bypassing the markdown parser.
    Images are expected to live in a 'maps/' subdirectory relative to the page.
    """
    header = (
        f'<div class="chapter-header">'
        f'<div class="ch-label">{_html.escape(novel_title)}</div>'
        f'<h2>Maps</h2>'
        f'</div>'
    )

    if image_paths:
        figures_parts = []
        for p in image_paths:
            if p.stem.endswith("_pretty"):
                continue
            pretty = p.with_name(f"{p.stem}_pretty{p.suffix}")
            nice = p.with_name(f"{p.stem}_nice{p.suffix}")
            preview = pretty if pretty.exists() else nice
            caption = _html.escape(p.stem.replace("_", " "))
            pretty_html = (
                f'<img src="maps/{_html.escape(preview.name)}" alt="{caption} pretty" '
                f'style="max-width:100%;border-radius:8px;border:1px solid rgba(0,0,0,.15);box-shadow:0 2px 12px rgba(0,0,0,.12);">'
                if preview.exists() else
                '<div style="min-height:180px;display:flex;align-items:center;justify-content:center;'
                'border:1px dashed rgba(0,0,0,.22);border-radius:8px;color:#777;font-style:italic;">'
                'Pretty preview not generated yet</div>'
            )
            figures_parts.append(
                f'<figure style="margin:0 0 2.5rem;">'
                f'<div style="display:grid;grid-template-columns:repeat(auto-fit,minmax(280px,1fr));gap:18px;align-items:start;">'
                f'<div><div style="font-size:11px;letter-spacing:.12em;text-transform:uppercase;color:#777;margin-bottom:6px;">VTT Tactical</div>'
                f'<img src="maps/{_html.escape(p.name)}" alt="{caption} tactical" '
                f'style="max-width:100%;border-radius:8px;border:1px solid rgba(0,0,0,.15);box-shadow:0 2px 12px rgba(0,0,0,.12);"></div>'
                f'<div><div style="font-size:11px;letter-spacing:.12em;text-transform:uppercase;color:#777;margin-bottom:6px;">Pretty Preview</div>'
                f'{pretty_html}</div>'
                f'</div>'
                f'<figcaption style="font-size:12px;color:#888;margin-top:8px;font-family:serif;font-style:italic;">{caption}</figcaption>'
                f'</figure>'
            )
        figures = "\n".join(figures_parts)
        body_html = (
            f'<h3 style="border-bottom:1px solid rgba(0,0,0,.15);padding-bottom:.4rem;margin-bottom:1.5rem;">Battle Maps</h3>'
            f'<div style="display:flex;flex-direction:column;gap:0;">{figures}</div>'
        )
    else:
        body_html = (
            f'<p style="color:#888;font-style:italic;">No maps generated for this mission.</p>'
            + (f'<pre style="font-size:11px;color:#666;white-space:pre-wrap;">{_html.escape(manifest_json)}</pre>' if manifest_json else "")
        )

    content = header + f'<div class="chapter-body">{body_html}</div>'
    return _page(f"Maps — {novel_title}", content, faction)


def render_index(
    novel_title: str,
    faction: str,
    tier: str,
    cr,
    player_name: str,
    chapters: list[dict],
    components: list[tuple[str, str]],  # [(label, filename), ...]
    chart_pack: str | None,
    map_count: int,
) -> str:
    """Render the index page with links to all components."""
    meta = (
        f"<strong>Faction:</strong> {_html.escape(faction)} &nbsp;|&nbsp; "
        f"<strong>Tier:</strong> {_html.escape(tier.upper())} &nbsp;|&nbsp; "
        f"<strong>CR:</strong> {cr} &nbsp;|&nbsp; "
        f"<strong>Claimed by:</strong> {_html.escape(player_name or 'Open')}"
    )

    # Chapter table
    ch_rows = "".join(
        f"<tr><td>{c['num']}</td><td>"
        f"<a href='chapter_{c['num']:02d}.html'>{_html.escape(c['title'])}</a>"
        f"</td><td>{c['word_count']:,}</td></tr>"
        for c in chapters
    )
    total_words = sum(c["word_count"] for c in chapters)
    novel_section = (
        f"<h2>Novel — {total_words:,} words</h2>"
        f"<table><tr><th>#</th><th>Chapter</th><th>Words</th></tr>{ch_rows}</table>"
    )

    # Box set cards
    cards = ""
    labels = {
        "dm_guide":      ("DM Guide",       "The real situation, NPC secrets, session pacing."),
        "module":        ("Module",          "Scene-by-scene play guide with decision trees."),
        "players_guide": ("Players Guide",   "Setting lore, faction primer, surface story."),
        "maps":          ("Maps",            f"{map_count} battle maps generated."),
        "chart_pack":    ("Chart Pack",      "Stat blocks, rumors, loot, encounter tables."),
        "session":       ("▶ Run Session",   "Tablet runner — scenes, initiative, HP, debrief form."),
    }
    for slug, fname in components:
        lbl, desc = labels.get(slug, (slug.replace("_", " ").title(), ""))
        cards += (
            f'<div class="index-card">'
            f'<h3><a href="{_html.escape(fname)}">{lbl}</a></h3>'
            f'<p>{desc}</p>'
            f'</div>'
        )
    if chart_pack:
        lbl, desc = labels["chart_pack"]
        cards += (
            f'<div class="index-card">'
            f'<h3><a href="{_html.escape(chart_pack)}">{lbl}</a></h3>'
            f'<p>{desc}</p>'
            f'</div>'
        )

    # Big session runner CTA if session.html was generated
    session_cta = ""
    has_session = any(slug == "session" for slug, _ in components)
    if has_session:
        session_cta = (
            '<div style="margin:20px 0 28px;text-align:center;">'
            '<a href="session.html" style="display:inline-block;padding:16px 40px;'
            'background:#c85320;color:white;font-size:18px;font-weight:bold;'
            'border-radius:10px;text-decoration:none;letter-spacing:.04em;'
            'box-shadow:0 4px 12px rgba(200,83,32,.4);">'
            '▶ Run This Session</a>'
            '<div style="font-size:12px;color:#888;margin-top:8px;">'
            'Scene tracker · Initiative · HP · Debrief</div>'
            '</div>'
        )

    content = (
        f'<div class="chapter-header">'
        f'<div class="ch-label">Tower of Last Chance — Mission Module</div>'
        f'<h2>{_html.escape(novel_title)}</h2>'
        f'</div>'
        f'<p style="margin-bottom:16px">{meta}</p>'
        + session_cta +
        f'<h2>Box Set Components</h2>'
        f'<div class="index-grid">{cards}</div>'
        + novel_section
    )

    return _page(f"{novel_title} — Index", content, faction)

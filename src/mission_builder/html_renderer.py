# ---------------------------------------------------------------------------
# Inline markdown → HTML
# ---------------------------------------------------------------------------

def _inline(text: str) -> str:
    """Convert inline markdown (bold, italic, code) to HTML."""
    text = _html.escape(text)
    # Bold-italic
    text = re.sub(r'\*\*\*(.+?)\*\*\*', r'<strong><em>\1</em></strong>', text)
    # Bold
    text = re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', text)
    # Italic
    text = re.sub(r'\*(.+?)\*', r'<em>\1</em>', text)
    # Inline code
    text = re.sub(r'`(.+?)`', r'<code>\1</code>', text)
    return text


# ---------------------------------------------------------------------------
# Block parser
# ---------------------------------------------------------------------------

def _parse_blocks(md: str) -> str:
    """Convert markdown text to HTML blocks."""
    lines    = md.splitlines()
    out      = []
    i        = 0
    stat_buf: list[str] = []
    in_table = False
    table_rows: list[list[str]] = []

    def flush_stat():
        if not stat_buf:
            return
        out.append('<div class="stat-block">')
        for ln in stat_buf:
            if re.match(r'^[-─═]{3,}$', ln.strip()):
                out.append('<div class="stat-divider"></div>')
            else:
                out.append(f'<div class="stat-line">{_inline(ln)}</div>')
        out.append('</div>')
        stat_buf.clear()

    def flush_table():
        if not table_rows:
            return
        out.append('<table>')
        for ri, row in enumerate(table_rows):
            tag = 'th' if ri == 0 else 'td'
            out.append('<tr>' + ''.join(f'<{tag}>{_inline(c)}</{tag}>' for c in row) + '</tr>')
        out.append('</table>')
        table_rows.clear()

    while i < len(lines):
        line = lines[i]
        stripped = line.strip()

        # ── Stat block lines (>> prefix) ──────────────────────────────
        if stripped.startswith('>> '):
            flush_table()
            stat_buf.append(stripped[3:])
            i += 1
            continue

        # Flush stat block if we hit a non->> line
        if stat_buf:
            flush_stat()

        # ── Table rows ─────────────────────────────────────────────────
        if stripped.startswith('|') and stripped.endswith('|'):
            if re.match(r'^\|[\s\-:|]+\|$', stripped):
                i += 1
                continue
            cells = [c.strip() for c in stripped.split('|') if c.strip()]
            table_rows.append(cells)
            i += 1
            continue

        if table_rows:
            flush_table()

        # ── READ ALOUD block ───────────────────────────────────────────
        # Matches: "📖 READ ALOUD:", "Read this:", "READ ALOUD:"
        if re.match(r'^(📖\s*)?READ\s+ALOUD\s*:', stripped, re.IGNORECASE) or \
           re.match(r'^Read\s+this\s*:', stripped, re.IGNORECASE):
            # Collect all following lines until next section marker or blank+non-indent
            label = re.sub(r'^(📖\s*)?READ\s+ALOUD\s*:|^Read\s+this\s*:', '', stripped, flags=re.IGNORECASE).strip()
            ra_lines = []
            if label:
                ra_lines.append(label)
            i += 1
            while i < len(lines):
                nxt = lines[i].strip()
                # Stop on a new section marker, blank line followed by new section, heading
                if not nxt:
                    # Peek ahead
                    if i + 1 < len(lines) and re.match(
                        r'^(📝|📋|👤|🎲|⚡|➡️|GM\s*NOTE|DM\s*NOTE|#{1,4}\s|>>)',
                        lines[i + 1].strip(), re.IGNORECASE
                    ):
                        break
                    ra_lines.append('')
                    i += 1
                    continue
                if re.match(r'^(📝|📋|👤|🎲|⚡|➡️|GM\s*NOTE|DM\s*NOTE|#)', nxt, re.IGNORECASE):
                    break
                ra_lines.append(nxt)
                i += 1
            content_html = ' '.join(ra_lines).strip()
            out.append(
                '<div class="read-aloud">'
                '<span class="ra-label">📖 Read Aloud to Players</span>'
                f'{_inline(content_html)}'
                '</div>'
            )
            continue

        # ── GM NOTE / DM NOTE box ──────────────────────────────────────
        if re.match(r'^(📝\s*)?(?:GM|DM)\s*NOTE\s*:', stripped, re.IGNORECASE) or \
           re.match(r'^(📝\s*DM\s+NOTES?)\s*:', stripped, re.IGNORECASE):
            label_text = re.sub(r'^(📝\s*)?(?:GM|DM)\s*NOTES?\s*:', '', stripped, flags=re.IGNORECASE).strip()
            note_lines = []
            if label_text:
                note_lines.append(label_text)
            i += 1
            while i < len(lines):
                nxt = lines[i].strip()
                if not nxt or re.match(r'^(📖|📋|👤|🎲|⚡|➡️|READ\s+ALOUD|Read\s+this|#{1,4}\s|>>)', nxt, re.IGNORECASE):
                    break
                note_lines.append(nxt)
                i += 1
            content_html = '<br>'.join(_inline(ln) for ln in note_lines if ln)
            out.append(
                '<div class="gm-note">'
                '<span class="gm-label">📝 GM / DM Only</span>'
                f'{content_html}'
                '</div>'
            )
            continue

        # ── Numbered area header: "N - Area Name" or "Area N. Name" ──
        m_area = re.match(r'^(\d+)\s*[-–.]\s*(.+)$', stripped)
        if m_area and len(stripped) < 80:
            num = m_area.group(1)
            name = m_area.group(2).strip()
            out.append(
                f'<div class="area-header">'
                f'<span class="area-num">{_html.escape(num)}</span>'
                f'<span class="area-name">{_inline(name)}</span>'
                f'</div>'
            )
            i += 1
            continue

        # ── Scene section labels (👤 NPCs PRESENT:, 🎲 MECHANICS:, etc.) ──
        m_sec = re.match(
            r'^(👤\s*NPCs?\s*PRESENT|🎲\s*MECHANICS?|⚡\s*WHAT\s*HAPPENS?|'
            r'📝\s*DM\s*NOTES?|👤\s*NPC|Actions?|Reactions?|Legendary\s*Actions?)\s*:?\s*$',
            stripped, re.IGNORECASE
        )
        if m_sec:
            out.append(f'<div class="scene-section">{_html.escape(stripped.lstrip("📖📝👤🎲⚡").strip())}</div>')
            i += 1
            continue

        # ── Transition line ➡️ TRANSITION: ──────────────────────────────
        if re.match(r'^➡️?\s*TRANSITION\s*:', stripped, re.IGNORECASE):
            content = re.sub(r'^➡️?\s*TRANSITION\s*:\s*', '', stripped, flags=re.IGNORECASE)
            out.append(f'<div class="transition">➡ {_inline(content)}</div>')
            i += 1
            continue

        # ── SIDEBAR ────────────────────────────────────────────────────
        if re.match(r'^>?\s*SIDEBAR:\s*', stripped, re.IGNORECASE):
            content = re.sub(r'^>?\s*SIDEBAR:\s*', '', stripped, flags=re.IGNORECASE)
            out.append(
                '<div class="sidebar">'
                '<div class="sidebar-title">◆ Sidebar</div>'
                f'<p>{_inline(content)}</p>'
                '</div>'
            )
            i += 1
            continue

        # ── SNIPPET ────────────────────────────────────────────────────
        if re.match(r'^>?\s*SNIPPET:\s*', stripped, re.IGNORECASE):
            content = re.sub(r'^>?\s*SNIPPET:\s*', '', stripped, flags=re.IGNORECASE)
            out.append(f'<div class="snippet">{_inline(content)}</div>')
            i += 1
            continue

        # ── DM note [DM: ...] ──────────────────────────────────────────
        m = re.match(r'^\[DM:\s*(.*?)\]$', stripped, re.IGNORECASE)
        if m:
            out.append(
                f'<div class="dm-note">'
                f'<span class="dm-label">DM Note</span>'
                f'{_inline(m.group(1))}'
                f'</div>'
            )
            i += 1
            continue

        # Generic blockquote (> text)
        if stripped.startswith('> '):
            content = stripped[2:]
            out.append(f'<blockquote><p>{_inline(content)}</p></blockquote>')
            i += 1
            continue

        # ── Headings ───────────────────────────────────────────────────
        if stripped.startswith('#### '):
            out.append(f'<h4>{_inline(stripped[5:])}</h4>')
            i += 1
            continue
        if stripped.startswith('### '):
            out.append(f'<h3>{_inline(stripped[4:])}</h3>')
            i += 1
            continue
        if stripped.startswith('## '):
            out.append(f'<h2>{_inline(stripped[3:])}</h2>')
            i += 1
            continue
        if stripped.startswith('# '):
            out.append(f'<h1>{_inline(stripped[2:])}</h1>')
            i += 1
            continue

        # ── Horizontal rule ────────────────────────────────────────────
        if re.match(r'^[-*_]{3,}$', stripped):
            out.append('<hr>')
            i += 1
            continue

        # ── Bullet list ────────────────────────────────────────────────
        if re.match(r'^[-*]\s+', stripped):
            items = []
            while i < len(lines) and re.match(r'^[-*]\s+', lines[i].strip()):
                items.append(f'<li>{_inline(lines[i].strip()[2:])}</li>')
                i += 1
            out.append('<ul>' + ''.join(items) + '</ul>')
            continue

        # ── Numbered list ──────────────────────────────────────────────
        if re.match(r'^\d+\.\s+', stripped):
            items = []
            while i < len(lines) and re.match(r'^\d+\.\s+', lines[i].strip()):
                content = re.sub(r'^\d+\.\s+', '', lines[i].strip())
                items.append(f'<li>{_inline(content)}</li>')
                i += 1
            out.append('<ol>' + ''.join(items) + '</ol>')
            continue

        # ── Empty line ─────────────────────────────────────────────────
        if not stripped:
            i += 1
            continue

        # ── Paragraph ─────────────────────────────────────────────────
        # Accumulate consecutive non-empty, non-special lines
        para_lines = []
        while i < len(lines):
            ln = lines[i].strip()
            if not ln:
                break
            if ln.startswith(('>> ', '> ', '#', '|', '-', '*', '[DM:')):
                break
            if re.match(r'^\d+\.\s+', ln):
                break
            para_lines.append(_inline(ln))
            i += 1
        if para_lines:
            out.append('<p>' + ' '.join(para_lines) + '</p>')
        else:
            i += 1

    flush_stat()
    flush_table()

    return '\n'.join(out)



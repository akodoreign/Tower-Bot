def _esc(t: str) -> str:
    return _html.escape(str(t or ""))


def _md(t: str) -> str:
    """Inline markdown on escaped text."""
    return _inline(str(t or ""))


def _render_stat_block(sb: dict) -> str:
    """Render one stat block dict into a styled HTML box."""
    lines = []
    name_line = _esc(sb.get("name", "Unknown"))
    count = sb.get("count", 1)
    if count and int(count) > 1:
        name_line += f" <span style='font-weight:normal;font-size:13px'>(×{count})</span>"
    lines.append(f'<div class="stat-line" style="font-size:17px;font-weight:bold;color:#2a0808;margin-bottom:6px">{name_line}</div>')
    if sb.get("size_type"):
        lines.append(f'<div class="stat-line" style="font-style:italic;color:#555;margin-bottom:8px">{_esc(sb["size_type"])}</div>')
    lines.append('<div class="stat-divider"></div>')
    for key in ("ac", "hp", "speed"):
        if sb.get(key):
            label = {"ac": "Armor Class", "hp": "Hit Points", "speed": "Speed"}[key]
            lines.append(f'<div class="stat-line"><strong>{label}</strong> {_esc(sb[key])}</div>')
    if sb.get("stats"):
        lines.append('<div class="stat-divider"></div>')
        lines.append(f'<div class="stat-line" style="font-family:Arial,sans-serif;font-size:13px">{_esc(sb["stats"])}</div>')
    lines.append('<div class="stat-divider"></div>')
    for key in ("saves", "skills", "resistances", "immunities", "senses", "languages", "cr"):
        if sb.get(key):
            label = key.replace("_", " ").title()
            if key == "cr":
                label = "Challenge"
            lines.append(f'<div class="stat-line"><strong>{label}</strong> {_esc(sb[key])}</div>')
    if sb.get("traits"):
        lines.append('<div class="stat-divider"></div>')
        for trait in sb["traits"]:
            lines.append(f'<div class="stat-line">{_md(trait)}</div>')
    if sb.get("actions"):
        lines.append('<div class="stat-divider"></div>')
        lines.append('<div class="stat-line" style="font-variant:small-caps;font-weight:bold;letter-spacing:1px;color:#7b1e1e;font-size:15px">Actions</div>')
        for action in sb["actions"]:
            lines.append(f'<div class="stat-line">{_md(action)}</div>')
    if sb.get("tactics"):
        lines.append('<div class="stat-divider"></div>')
        lines.append(f'<div class="stat-line" style="font-style:italic;color:#3a3a3a">'
                     f'<strong>Tactics:</strong> {_esc(sb["tactics"])}</div>')
    if sb.get("if_lose"):
        lines.append(f'<div class="stat-line" style="font-style:italic;color:#5a2020">'
                     f'<strong>If players lose:</strong> {_esc(sb["if_lose"])}</div>')
    return (
        '<div class="stat-block">'
        + "\n".join(lines) +
        '</div>'
    )


def _render_npc_block(npc: dict) -> str:
    """Render one NPC truth sheet."""
    name = _esc(npc.get("name", "Unknown NPC"))
    role = _esc(npc.get("role", ""))
    lines = [
        f'<div style="margin:16px 0 8px;padding:10px 16px;background:#f8f4ec;'
        f'border-left:4px solid #b8923a;border-radius:0 4px 4px 0">',
        f'<div style="font-weight:bold;font-size:16px;color:#2a1808">{name}'
        + (f' <span style="font-weight:normal;font-style:italic;color:#666;font-size:14px">— {role}</span>' if role else "")
        + '</div>',
    ]
    for field in ("wants", "knows", "hides"):
        if npc.get(field):
            label = field.capitalize()
            lines.append(
                f'<div style="font-family:Arial,sans-serif;font-size:14px;margin-top:4px">'
                f'<span style="font-weight:bold;color:#7b1e1e;text-transform:uppercase;'
                f'font-size:11px;letter-spacing:1px">{label}:</span> '
                f'{_esc(npc[field])}</div>'
            )
    if npc.get("branches"):
        for branch in npc["branches"]:
            lines.append(
                f'<div style="font-family:Arial,sans-serif;font-size:13px;'
                f'margin-top:6px;padding:6px 10px;background:#f0f0e8;'
                f'border-radius:3px;border-left:2px solid #c8a84a">'
                f'{_md(branch)}</div>'
            )
    lines.append('</div>')
    return "\n".join(lines)


def _render_scene(scene: dict) -> str:
    """Render one complete scene section."""
    num   = str(scene.get("num", "?"))
    name  = _esc(scene.get("name", "").upper())
    parts = []

    # Area header
    parts.append(
        f'<div class="area-header" style="margin-top:48px">'
        f'<span class="area-num">{num}</span>'
        f'<span class="area-name">{name}</span>'
        f'</div>'
    )

    # Read-aloud
    if scene.get("read_aloud"):
        parts.append(
            '<div class="read-aloud">'
            '<span class="ra-label">📖 Read Aloud to Players</span>'
            f'<em>{_esc(scene["read_aloud"])}</em>'
            '</div>'
        )

    # GM note
    if scene.get("gm_note"):
        note_html = "<br>".join(_md(ln) for ln in scene["gm_note"].splitlines() if ln.strip())
        parts.append(
            '<div class="gm-note">'
            '<span class="gm-label">📝 GM / DM Only</span>'
            f'{note_html}'
            '</div>'
        )

    # NPCs
    if scene.get("npcs"):
        parts.append('<div class="scene-section">👤 NPCs Present</div>')
        for npc in scene["npcs"]:
            parts.append(_render_npc_block(npc))

    # Mechanics / branches (non-NPC-specific)
    if scene.get("mechanics"):
        parts.append('<div class="scene-section">🎲 Mechanics &amp; Branches</div>')
        mech_lines = []
        for m in scene["mechanics"]:
            mech_lines.append(f'<li style="margin-bottom:8px">{_md(m)}</li>')
        parts.append('<ul style="margin:8px 0 0 20px;font-family:Arial,sans-serif;font-size:15px">'
                     + "".join(mech_lines) + '</ul>')

    # Clues
    if scene.get("clues"):
        parts.append('<div class="scene-section">🔍 Three-Clue Structure</div>')
        clue_lines = "".join(
            f'<li style="margin-bottom:6px"><strong>{_esc(c.split(":")[0])}:</strong> '
            f'{_esc(":".join(c.split(":")[1:]).strip())}</li>'
            if ":" in c else f'<li>{_esc(c)}</li>'
            for c in scene["clues"]
        )
        parts.append(f'<ul style="margin:8px 0 0 20px;font-family:Arial,sans-serif;font-size:15px">{clue_lines}</ul>')

    # Stat blocks
    if scene.get("stat_blocks"):
        parts.append('<div class="scene-section">⚔️ Stat Blocks</div>')
        for sb in scene["stat_blocks"]:
            parts.append(_render_stat_block(sb))

    # What happens / outcome bullets
    if scene.get("what_happens"):
        parts.append('<div class="scene-section">⚡ What Happens</div>')
        wh_lines = "".join(
            f'<li style="margin-bottom:8px">{_md(item)}</li>'
            for item in scene["what_happens"]
        )
        parts.append('<ul style="margin:8px 0 0 20px;font-family:Arial,sans-serif;font-size:15px">'
                     + wh_lines + '</ul>')

    # Transition
    if scene.get("transition"):
        parts.append(f'<div class="transition">➡ {_esc(scene["transition"])}</div>')

    return "\n".join(parts)


def render_module_structured(module_data: dict) -> str:
    """
    Render a module from structured scene data.

    module_data keys:
        title (str), faction (str), tier (str), cr (int|str),
        party_level (int|str), runtime (str), players (str),
        hook (str)            — read-aloud hook text shown before scene 1,
        hook_note (str)       — GM-only context behind the hook,
        scenes (list[dict])   — each scene dict, see _render_scene(),
        rewards (str)         — reward summary,
        dc_table (list[list]) — optional [["Scene","Check","DC","Success","Failure"],...]

    Returns a full standalone HTML string.
    """
    title      = module_data.get("title", "Untitled Module")
    faction    = module_data.get("faction", "")
    tier       = module_data.get("tier", "Standard")
    cr         = module_data.get("cr", "?")
    plevel     = module_data.get("party_level", "?")
    runtime    = module_data.get("runtime", "2-3 hours")
    players    = module_data.get("players", "4-6")
    scenes     = module_data.get("scenes", [])

    # Cover
    fc   = _faction_color(faction)
    cover = (
        f'<div class="cover" style="--faction:{fc}">'
        f'<div class="faction-label">{_esc(faction.upper())}</div>'
        f'<div class="ornament">✦ ✦ ✦</div>'
        f'<h1>{_esc(title)}</h1>'
        f'<div class="subtitle">D&amp;D 5e 2024 · One-Shot Module</div>'
        f'<div class="meta-block">'
        f'Tier: {_esc(tier.upper())} &nbsp;|&nbsp; CR {_esc(str(cr))} &nbsp;|&nbsp; '
        f'Party Level {_esc(str(plevel))} &nbsp;|&nbsp; {_esc(players)} Players'
        f'<br>Runtime: {_esc(runtime)} &nbsp;|&nbsp; {len(scenes)} Areas'
        f'</div>'
        f'</div>'
    )

    body_parts = ['<div class="page-body">']

    # Hook
    if module_data.get("hook"):
        body_parts.append(
            '<h2 style="margin-top:32px">Hook</h2>'
            '<div class="read-aloud">'
            '<span class="ra-label">📖 Read to Players Before Play Begins</span>'
            f'<em>{_esc(module_data["hook"])}</em>'
            '</div>'
        )
    if module_data.get("hook_note"):
        note_html = "<br>".join(_md(ln) for ln in module_data["hook_note"].splitlines() if ln.strip())
        body_parts.append(
            '<div class="gm-note">'
            '<span class="gm-label">📝 GM Context</span>'
            f'{note_html}'
            '</div>'
        )

    # Scene count callout
    beat_labels = {1: "Hook/Approach", 2: "Investigation", 3: "Complication",
                   4: "Climax", 5: "Resolution", 6: "Epilogue", 7: "Aftermath"}
    toc_rows = "".join(
        f'<tr><td style="font-weight:bold">{s.get("num","")}</td>'
        f'<td>{_esc(s.get("name","").title())}</td>'
        f'<td style="color:#666;font-style:italic">{_esc(s.get("beat_label", beat_labels.get(int(s.get("num",0)), "")))}</td></tr>'
        for s in scenes
    )
    body_parts.append(
        '<table style="margin-top:28px">'
        '<tr><th>#</th><th>Area</th><th>Beat</th></tr>'
        f'{toc_rows}</table>'
    )

    # Scenes
    body_parts.append('<h2 style="margin-top:48px">Areas</h2>')
    for scene in scenes:
        body_parts.append(_render_scene(scene))
        body_parts.append('<hr>')

    # Rewards
    if module_data.get("rewards"):
        body_parts.append('<h2>Rewards</h2>')
        for line in module_data["rewards"].splitlines():
            if line.strip():
                body_parts.append(f'<p style="font-family:Arial,sans-serif;font-size:15px">{_md(line)}</p>')

    # DC reference table
    if module_data.get("dc_table"):
        body_parts.append('<h2>Quick DC Reference</h2>')
        tbl_rows = []
        for ri, row in enumerate(module_data["dc_table"]):
            tag = "th" if ri == 0 else "td"
            tbl_rows.append(
                "<tr>" + "".join(f"<{tag}>{_esc(str(c))}</{tag}>" for c in row) + "</tr>"
            )
        body_parts.append("<table>" + "".join(tbl_rows) + "</table>")

    body_parts.append('</div>')

    content = cover + "\n".join(body_parts)
    return _page(f"Module — {title}", content, faction)



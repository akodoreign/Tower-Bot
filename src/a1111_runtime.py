"""Model selection helpers for image jobs.

Kept under the old module name so existing imports keep working. Images are
generated by ComfyUI (src/comfy_client.py): "switching" a model only records
which recipe the next request uses, and there is nothing to cool down because
every job already waits its turn on the GPU queue.
"""

from __future__ import annotations

from src import comfy_client


async def ensure_a1111_model(model: str, *, label: str = "image", url: str | None = None) -> bool:
    """Select the recipe for `model` for the next generate() call."""
    comfy_client.set_checkpoint(model)
    return True


async def cool_down_a1111_after_generation(*, cooldown: float = 45) -> None:
    """No-op: the GPU queue serialises jobs, so no settle time is needed."""
    return None

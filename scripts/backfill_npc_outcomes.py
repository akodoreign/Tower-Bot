"""
backfill_npc_outcomes.py

Fetches all messages from the mission results Discord channel, matches them to
completed NPC missions that have no outcome record, and inserts mission_outcomes rows.

Each outcome is generated by the LLM using:
  - The Discord completion/failure notice text
  - The NPC party's profile (visual, skills, history) from party_profiles table
  - The mission body and metadata

Usage:
    python scripts/backfill_npc_outcomes.py [--dry-run]

Personal missions (personal_for IS NOT NULL) are excluded.
"""


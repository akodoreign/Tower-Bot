"""
import_npcs_to_ddb.py — Batch-import all 199 campaign NPCs to DDB homebrew.

Reads from scripts/npc_ddb_staging.json (generated by npc_ddb_builder.py).
Uploads portraits where available. Adds movement speeds.
Logs results to logs/npc_ddb_import.log.

Run from project root:
    python scripts/import_npcs_to_ddb.py

Resumes cleanly: skips NPCs already imported (checks log for names).
"""
